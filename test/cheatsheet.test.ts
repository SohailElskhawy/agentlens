import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { symlinkSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tmp, put } from './helpers.ts';
import { openDb, upsertProject, upsertFindings } from '../src/db.ts';
import { generateCheatsheet, formatCheatsheetMarkdown } from '../src/cheatsheet.ts';
import { MAX_BOUNDED_READ_BYTES } from '../src/ai/constants.ts';

const CLI = fileURLToPath(new URL('../src/cli.ts', import.meta.url));
const { CLAUDE_CONFIG_DIR: _c, CODEX_HOME: _x, ...baseEnv } = process.env;
const runCli = (args: string[], env: Record<string, string>) =>
  execFileSync(process.execPath, ['--no-warnings=ExperimentalWarning', CLI, ...args], {
    env: { ...baseEnv, ...env },
    encoding: 'utf8',
    stdio: 'pipe',
  });

test('1. extracts exported functions, interfaces, types, and constants from top hot_files findings in temp project root, ordered by read count, and formats compact markdown block', () => {
  const projDir = tmp();
  const db = openDb(':memory:');
  const pid = upsertProject(db, projDir, 'test-project');

  put(
    join(projDir, 'src/db.ts'),
    `import { DatabaseSync } from 'node:sqlite';
export type DB = DatabaseSync;
export interface DBConfig {
  path: string;
}
export const DEFAULT_TIMEOUT = 5000;
export let activeConnections = 0;
export function openDb(path: string): DB {
  return new DatabaseSync(path);
}
export async function query(sql: string, params: unknown[] = []): Promise<unknown> {
  return null;
}
export class ConnectionPool {
  connect() {}
}
`,
  );

  put(
    join(projDir, 'src/utils.ts'),
    `export function formatNumber(n: number): string {
  return n.toLocaleString();
}
export const VERSION = '1.0.0';
`,
  );

  upsertFindings(db, [
    {
      id: 'finding:hot:1',
      rule: 'hot_files',
      projectId: pid,
      sessionId: null,
      confidence: 'high',
      confidenceReason: 'Read repeatedly',
      evidence: { file: 'src/utils.ts', reads: 8 },
      estTokensWeek: 16000,
      firstSeen: Date.now() - 10000,
      lastSeen: Date.now(),
    },
    {
      id: 'finding:hot:2',
      rule: 'hot_files',
      projectId: pid,
      sessionId: null,
      confidence: 'high',
      confidenceReason: 'Read repeatedly',
      evidence: { files: [{ file: 'src/db.ts', reads: 14 }] },
      estTokensWeek: 28000,
      firstSeen: Date.now() - 10000,
      lastSeen: Date.now(),
    },
  ]);

  const res = generateCheatsheet(db, { projectRoot: projDir });

  assert.equal(res.projectId, pid);
  assert.equal(res.projectName, 'test-project');
  assert.equal(res.files.length, 2);

  // Sorted by reads descending
  assert.equal(res.files[0].relativePath, 'src/db.ts');
  assert.equal(res.files[0].reads, 14);
  assert.deepEqual(res.files[0].exports, [
    'type DB',
    'interface DBConfig',
    'const DEFAULT_TIMEOUT',
    'const activeConnections',
    'fn openDb(path: string)',
    'fn query(sql: string, params: unknown[] = [])',
    'class ConnectionPool',
  ]);

  assert.equal(res.files[1].relativePath, 'src/utils.ts');
  assert.equal(res.files[1].reads, 8);
  assert.deepEqual(res.files[1].exports, [
    'fn formatNumber(n: number)',
    'const VERSION',
  ]);

  const expectedMarkdown = [
    '## Architecture Cheat-Sheet (test-project)',
    '<!-- Generated by agentlens cheatsheet from top hot_files -->',
    '- `src/db.ts` (14 reads): `type DB`, `interface DBConfig`, `const DEFAULT_TIMEOUT`, `const activeConnections`, `fn openDb(path: string)`, `fn query(sql: string, params: unknown[] = [])`, `class ConnectionPool`',
    '- `src/utils.ts` (8 reads): `fn formatNumber(n: number)`, `const VERSION`',
  ].join('\n');

  assert.equal(formatCheatsheetMarkdown(res), expectedMarkdown);
  assert.equal(res.markdown, expectedMarkdown);
});

test('2. refuses symlinks escaping root and skips files larger than MAX_BOUNDED_READ_BYTES (64 KiB)', () => {
  const projDir = tmp();
  const outsideDir = tmp();
  const db = openDb(':memory:');
  const pid = upsertProject(db, projDir, 'secure-project');

  // External secret file
  const secretPath = join(outsideDir, 'secret.ts');
  put(secretPath, 'export const SECRET_KEY = "super-secret";\n');

  // Symlink escaping root
  symlinkSync(secretPath, join(projDir, 'escaped-secret.ts'));

  // Oversized file (> 64 KiB)
  const oversizedContent = 'export const OVERSIZED = 1;\n' + ' '.repeat(MAX_BOUNDED_READ_BYTES + 1024);
  put(join(projDir, 'oversized.ts'), oversizedContent);

  // Valid small file
  put(join(projDir, 'valid.ts'), 'export function safeHandler(): void {}\n');

  upsertFindings(db, [
    {
      id: 'finding:hot:symlink',
      rule: 'hot_files',
      projectId: pid,
      sessionId: null,
      confidence: 'high',
      confidenceReason: 'Hot symlink',
      evidence: { target: 'escaped-secret.ts', reads: 50 },
      estTokensWeek: 100000,
      firstSeen: Date.now(),
      lastSeen: Date.now(),
    },
    {
      id: 'finding:hot:oversized',
      rule: 'hot_files',
      projectId: pid,
      sessionId: null,
      confidence: 'high',
      confidenceReason: 'Hot oversized file',
      evidence: { file: 'oversized.ts', reads: 40 },
      estTokensWeek: 80000,
      firstSeen: Date.now(),
      lastSeen: Date.now(),
    },
    {
      id: 'finding:hot:valid',
      rule: 'hot_files',
      projectId: pid,
      sessionId: null,
      confidence: 'high',
      confidenceReason: 'Hot valid file',
      evidence: { file: 'valid.ts', reads: 10 },
      estTokensWeek: 20000,
      firstSeen: Date.now(),
      lastSeen: Date.now(),
    },
  ]);

  const res = generateCheatsheet(db, { projectRoot: projDir });

  assert.equal(res.files.length, 1);
  assert.equal(res.files[0].relativePath, 'valid.ts');
  assert.equal(res.files[0].reads, 10);
  assert.deepEqual(res.files[0].exports, ['fn safeHandler()']);
});

test('3. respects --top N limit and handles projects with zero hot_files gracefully', () => {
  const projDir = tmp();
  const db = openDb(':memory:');
  const pid = upsertProject(db, projDir, 'top-project');

  for (let i = 1; i <= 6; i++) {
    put(join(projDir, `file${i}.ts`), `export const ITEM_${i} = ${i};\n`);
  }

  upsertFindings(
    db,
    [1, 2, 3, 4, 5, 6].map((i) => ({
      id: `finding:hot:${i}`,
      rule: 'hot_files',
      projectId: pid,
      sessionId: null,
      confidence: 'high' as const,
      confidenceReason: `Read count ${i * 5}`,
      evidence: { file: `file${i}.ts`, reads: i * 5 },
      estTokensWeek: i * 10000,
      firstSeen: Date.now(),
      lastSeen: Date.now(),
    })),
  );

  // Top 3 requested
  const resTop3 = generateCheatsheet(db, { projectRoot: projDir, top: 3 });
  assert.equal(resTop3.files.length, 3);
  assert.equal(resTop3.files[0].relativePath, 'file6.ts');
  assert.equal(resTop3.files[0].reads, 30);
  assert.equal(resTop3.files[1].relativePath, 'file5.ts');
  assert.equal(resTop3.files[1].reads, 25);
  assert.equal(resTop3.files[2].relativePath, 'file4.ts');
  assert.equal(resTop3.files[2].reads, 20);

  // Top clamped: top < 1 clamps to 1
  const resClampMin = generateCheatsheet(db, { projectRoot: projDir, top: 0 });
  assert.equal(resClampMin.files.length, 1);

  // Top default: 5 files
  const resDefault = generateCheatsheet(db, { projectRoot: projDir });
  assert.equal(resDefault.files.length, 5);

  // Empty project with zero hot_files
  const emptyDir = tmp();
  const emptyDb = openDb(':memory:');
  upsertProject(emptyDb, emptyDir, 'empty-project');
  const resEmpty = generateCheatsheet(emptyDb, { projectRoot: emptyDir });
  assert.equal(resEmpty.files.length, 0);
  assert.equal(resEmpty.markdown, 'No hot_files with exported symbols found for empty-project.');
});

test('4. CLI agentlens cheatsheet --project <tmp> --json and markdown mode work end-to-end with isolated AGENTLENS_DATA_DIR', () => {
  const dataDir = tmp();
  const projDir = tmp();
  const dbPath = join(dataDir, 'agentlens.db');

  const db = openDb(dbPath);
  const pid = upsertProject(db, projDir, 'cli-test-proj');

  put(
    join(projDir, 'src/index.ts'),
    `export function startServer(port: number): void {}
export const APP_NAME = 'CLI Test';
`,
  );

  upsertFindings(db, [
    {
      id: 'finding:hot:cli',
      rule: 'hot_files',
      projectId: pid,
      sessionId: null,
      confidence: 'high',
      confidenceReason: 'Hot file CLI test',
      evidence: { file: 'src/index.ts', reads: 12 },
      estTokensWeek: 24000,
      firstSeen: Date.now(),
      lastSeen: Date.now(),
    },
  ]);
  db.close();

  // 1. JSON mode
  const jsonOut = runCli(['cheatsheet', '--project', projDir, '--json'], {
    AGENTLENS_DATA_DIR: dataDir,
  });
  const parsed = JSON.parse(jsonOut);
  assert.equal(parsed.projectName, 'cli-test-proj');
  assert.equal(parsed.files.length, 1);
  assert.equal(parsed.files[0].relativePath, 'src/index.ts');
  assert.equal(parsed.files[0].reads, 12);
  assert.deepEqual(parsed.files[0].exports, ['fn startServer(port: number)', 'const APP_NAME']);

  // 1b. Positional project argument
  const posJsonOut = runCli(['cheatsheet', projDir, '--json'], {
    AGENTLENS_DATA_DIR: dataDir,
  });
  const posParsed = JSON.parse(posJsonOut);
  assert.equal(posParsed.projectName, 'cli-test-proj');
  assert.equal(posParsed.files.length, 1);

  // 2. Markdown mode
  const mdOut = runCli(['cheatsheet', '--project', projDir], {
    AGENTLENS_DATA_DIR: dataDir,
  });
  assert.ok(mdOut.includes('## Architecture Cheat-Sheet (cli-test-proj)'));
  assert.ok(mdOut.includes('<!-- Generated by agentlens cheatsheet from top hot_files -->'));
  assert.ok(mdOut.includes('- `src/index.ts` (12 reads): `fn startServer(port: number)`, `const APP_NAME`'));

  // 3. Graceful handling of project without hot files
  const emptyProj = tmp();
  const emptyOut = runCli(['cheatsheet', '--project', emptyProj], {
    AGENTLENS_DATA_DIR: dataDir,
  });
  assert.ok(emptyOut.includes('No hot_files with exported symbols found for'));
});

test('5. falls back from hash-only findings to bounded repository sources in deterministic order', () => {
  const root = tmp();
  const db = openDb(':memory:');
  const pid = upsertProject(db, root, 'fallback');
  put(join(root, 'src/index.ts'), 'export const INDEX = 1;\n');
  put(join(root, 'src/db.ts'), 'export const DB = 1;\n');
  put(join(root, 'src/z.ts'), 'export const Z = 1;\n' + ' '.repeat(20));
  put(join(root, 'src/a.ts'), 'export const A = 1;\n' + ' '.repeat(20));
  put(join(root, 'src/large.ts'), 'export const LARGE = 1;\n' + ' '.repeat(MAX_BOUNDED_READ_BYTES));
  put(join(root, 'src/nested/hidden.ts'), 'export const HIDDEN = 1;\n');
  symlinkSync(join(root, 'src/z.ts'), join(root, 'src/cli.ts'));
  upsertFindings(db, [{ id: 'hash', rule: 'hot_files', projectId: pid, sessionId: null,
    confidence: 'high', confidenceReason: 'reads', evidence: { argsHash: 'abc', reads: 100 },
    estTokensWeek: 1, firstSeen: Date.now(), lastSeen: Date.now() }]);
  const res = generateCheatsheet(db, { projectRoot: root, top: 3 });
  assert.deepEqual(res.files.map(f => f.relativePath), ['src/index.ts', 'src/db.ts', 'src/a.ts']);
  assert.ok(res.files.every(f => f.reads === 0));
  assert.match(res.markdown, /repository source/);
  assert.doesNotMatch(res.markdown, /100 reads/);
  const empty = generateCheatsheet(openDb(':memory:'), { projectRoot: root, top: 4 });
  assert.deepEqual(empty.files.map(f => f.relativePath), ['src/index.ts', 'src/db.ts', 'src/a.ts', 'src/z.ts']);
});

